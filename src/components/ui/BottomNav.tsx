export function BottomNav() {
  const pathname = usePathname();

  // Check if current path matches or starts with the nav item's href
  const isActive = (href: string) => {
    if (href === '/home') {
      return pathname === '/home' || pathname === '/';
    }
    return pathname.startsWith(href);
  };

  return (
    <nav
      className="fixed bottom-0 left-0 right-0 z-50 border-t border-stone-200 bg-white/95 backdrop-blur-lg safe-area-bottom dark:border-stone-700 dark:bg-stone-900/95"
      role="navigation"
      aria-label="Main navigation"
    >
      <div className="mx-auto flex max-w-2xl items-center justify-around">
        {navItems.map((item) => {
          const active = isActive(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex min-h-[56px] flex-1 flex-col items-center justify-center gap-1 transition-colors ${
                active
                  ? 'text-amber-600 dark:text-amber-400'
                  : 'text-stone-500 hover:text-stone-700 dark:text-stone-400 dark:hover:text-stone-200'
              }`}
              aria-current={active ? 'page' : undefined}
            >
              <span className="relative">
                {active ? item.activeIcon : item.icon}
                {/* Active indicator dot */}
                {active && (
                  <span className="absolute -bottom-1 left-1/2 h-1 w-1 -translate-x-1/2 rounded-full bg-amber-600 dark:bg-amber-400" />
                )}
              </span>
              <span className={`text-xs font-medium ${active ? 'font-semibold' : ''}`}>
                {item.label}
              </span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
